import { APP_FILTER } from '@nestjs/core';
import { Module } from '@nestjs/common';
import { PlatformModule } from '@lark-apaas/fullstack-nestjs-core';

import { GlobalExceptionFilter } from './common/filters/exception.filter';
import { ForumTaskModule } from './modules/forum-task/forum-task.module';
import { ForumDecisionModule } from './modules/forum-decision/forum-decision.module';
import { ForumNoticeModule } from './modules/forum-notice/forum-notice.module';
import { ForumOptionModule } from './modules/forum-option/forum-option.module';
import { ViewModule } from './modules/view/view.module';

@Module({
  imports: [
    // 平台 Module，提供平台能力
    PlatformModule.forRoot(),
    // ====== @route-section: business-modules START ======
    // Place all business modules here.Do NOT add fallback modules here.
    ForumTaskModule,
    ForumDecisionModule,
    ForumNoticeModule,
    ForumOptionModule,
    // ====== @route-section: business-modules END ======

    // ⚠️ @route-order: last
    // ViewModule is the fallback route module, must be registered last.
    ViewModule,
  ],
  providers: [
    {
      provide: APP_FILTER,
      useClass: GlobalExceptionFilter,
    },
  ],
})
export class AppModule {}
